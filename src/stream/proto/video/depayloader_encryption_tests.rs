/// A host that sends plaintext although encryption was negotiated must not be accepted,
/// no matter if the size matches that of a plaintext packet or that of an encrypted one.
#[test]
fn plaintext_is_never_accepted() {
    let mut plain_payloader = VideoPayloader::new(payloader_config(100, None));
    plain_payloader
        .push_frame(0, None, ServerFrameType::Idr, &frame_data())
        .expect("test frame should be packetized");
    let packets = drain(&mut plain_payloader);

    let mut depayloader = depayloader(KEY);
    for packet in &packets {
        depayloader.handle_packet(packet).unwrap();
    }
    assert_untouched(&depayloader);
    assert_eq!(
        depayloader.decryption_stats().unwrap().dropped_invalid_size,
        packets.len() as u64
    );

    // Same size as an encrypted packet, so this one has to fail the authentication
    for packet in &packets {
        let mut same_size = vec![0; EncryptedVideoHeader::SIZE];
        same_size.extend_from_slice(packet);

        depayloader.handle_packet(&same_size).unwrap();
    }
    assert_untouched(&depayloader);
    assert_eq!(
        depayloader
            .decryption_stats()
            .unwrap()
            .dropped_unauthenticated,
        packets.len() as u64
    );
}

#[test]
fn invalid_sizes_are_dropped() {
    let packet = &encrypted_packets(None)[0];
    let mut depayloader = depayloader(KEY);

    let mut too_long = packet.to_vec();
    too_long.push(0);

    let datagrams: [&[u8]; 5] = [
        &[],
        &packet[0..1],
        &packet[0..EncryptedVideoHeader::SIZE],
        &packet[0..packet.len() - 1],
        &too_long,
    ];
    for datagram in datagrams {
        depayloader.handle_packet(datagram).unwrap();
        assert_untouched(&depayloader);
    }

    assert_eq!(
        depayloader.decryption_stats().unwrap().dropped_invalid_size,
        5
    );
}

#[test]
fn valid_packets_are_accepted_after_failures() {
    let packets = encrypted_packets(None);
    let mut depayloader = depayloader(KEY);

    for packet in &packets {
        let mut tampered = packet.to_vec();
        tampered[40] ^= 0xFF;
        depayloader.handle_packet(&tampered).unwrap();
        depayloader.handle_packet(&[0; 3]).unwrap();

        depayloader.handle_packet(packet).unwrap();
    }

    assert_frame(&depayloader, 1, &frame_data());
}

// -- The unauthenticated frame number

/// This hint isn't authenticated, so raising it can't change the frame this packet belongs to.
#[test]
fn raised_frame_number_cant_change_the_frame() {
    let mut depayloader = depayloader(KEY);

    for packet in &encrypted_packets(None) {
        let mut packet = packet.to_vec();
        packet[12..16].copy_from_slice(&1000u32.to_le_bytes());
        depayloader.handle_packet(&packet).unwrap();
    }

    assert_eq!(
        depayloader.known_frames().collect::<Vec<_>>(),
        [FrameIndex(1)]
    );
    assert_frame(&depayloader, 1, &frame_data());
}

/// A host that doesn't send the hint must be decrypted, but the real frame index still counts.
#[test]
fn zero_frame_number_is_no_way_around_the_stale_check() {
    let mut depayloader = depayloader(KEY);
    depayloader.set_min_frame(FrameIndex(2));

    let mut packet = encrypted_packets(None)[0].to_vec();
    packet[12..16].copy_from_slice(&0u32.to_le_bytes());
    depayloader.handle_packet(&packet).unwrap();

    let stats = depayloader.decryption_stats().unwrap();
    assert_eq!((stats.authenticated, stats.dropped_stale), (1, 1));
    assert_eq!(depayloader.known_frames().count(), 0);
    assert!(depayloader.packets.is_empty());
}

#[test]
fn stale_frame_number_skips_decryption() {
    let mut depayloader = depayloader(KEY);
    depayloader.set_min_frame(FrameIndex(2));

    depayloader
        .handle_packet(&encrypted_packets(None)[0])
        .unwrap();

    let stats = depayloader.decryption_stats().unwrap();
    assert_eq!((stats.authenticated, stats.dropped_stale), (0, 1));
    assert_eq!(depayloader.known_frames().count(), 0);
}

#[test]
fn min_frame_cant_decrease() {
    let mut depayloader = depayloader(KEY);
    depayloader.set_min_frame(FrameIndex(2));
    depayloader.set_min_frame(FrameIndex(1));

    depayloader
        .handle_packet(&encrypted_packets(None)[0])
        .unwrap();

    assert_eq!(depayloader.known_frames().count(), 0);
}

